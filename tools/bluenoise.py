#!/usr/bin/env python3
"""
Write source/BlueNoise.h: a 64x64 blue-noise threshold mask by Ulichney's
void-and-cluster method (Robert Ulichney, "The void-and-cluster method for
dither array generation", Proc. SPIE 1913, 1993).

Every cell gets a rank 0..4095. A binary pattern's "energy" at a cell is the
sum, over its set cells, of a toroidal Gaussian (sigma 1.5) centred on each:
the tightest cluster is the set cell with the most energy, the largest void
the empty cell with the least.

  1. A seed pattern of 409 cells (a tenth), placed by a PCG hash, relaxed by
     moving its tightest cluster to its largest void until the move would put
     it back where it was.
  2. Phase 1: the seed's cells ranked by removing the tightest cluster
     again and again, highest rank first.
  3. Phases 2 and 3: from the seed, the largest void filled again and again,
     ranks counting up, until every cell has one. (Phase 3's "tightest
     cluster of the empty cells" is the same cell as phase 2's largest void,
     because the two energies sum to a constant.)

Deterministic: no random number generator but the hash, ties to the lowest
index, and only element-wise float64 arithmetic in a fixed order, so the same
numpy gives the same mask anywhere. tools/verify.sh regenerates it and diffs.

    python3 tools/bluenoise.py > source/BlueNoise.h
"""

import sys

import numpy as np

SIZE = 64
SIGMA = 1.5
SEED_FRACTION = 10


def pcg(v):
    state = (v * 747796405 + 2891336453) & 0xFFFFFFFF
    word = (((state >> ((state >> 28) + 4)) ^ state) * 277803737) & 0xFFFFFFFF
    return ((word >> 22) ^ word) & 0xFFFFFFFF


def kernel():
    d = np.arange(SIZE)
    d = np.minimum(d, SIZE - d).astype(np.float64)
    return np.exp(-(d[:, None] ** 2 + d[None, :] ** 2) / (2.0 * SIGMA * SIGMA))


K = kernel()


def splat(energy, cell, sign):
    y, x = divmod(cell, SIZE)
    energy += sign * np.roll(np.roll(K, y, axis=0), x, axis=1)


def tightest(pattern, energy):
    masked = np.where(pattern, energy, -np.inf).ravel()
    return int(np.argmax(masked))


def largest_void(pattern, energy):
    masked = np.where(pattern, np.inf, energy).ravel()
    return int(np.argmin(masked))


def main():
    n = SIZE * SIZE
    seed_count = n // SEED_FRACTION

    pattern = np.zeros((SIZE, SIZE), dtype=bool)
    energy = np.zeros((SIZE, SIZE), dtype=np.float64)
    placed = 0
    i = 0
    while placed < seed_count:
        cell = pcg(i) % n
        i += 1
        if pattern.flat[cell]:
            continue
        pattern.flat[cell] = True
        splat(energy, cell, 1.0)
        placed += 1

    for _ in range(100000):
        cluster = tightest(pattern, energy)
        pattern.flat[cluster] = False
        splat(energy, cluster, -1.0)
        void = largest_void(pattern, energy)
        pattern.flat[void] = True
        splat(energy, void, 1.0)
        if void == cluster:
            break
    else:
        sys.exit("bluenoise: the seed pattern did not settle")

    rank = np.full(n, -1, dtype=np.int64)

    p1, e1 = pattern.copy(), energy.copy()
    for r in range(seed_count - 1, -1, -1):
        cluster = tightest(p1, e1)
        p1.flat[cluster] = False
        splat(e1, cluster, -1.0)
        rank[cluster] = r

    p2, e2 = pattern.copy(), energy.copy()
    for r in range(seed_count, n):
        void = largest_void(p2, e2)
        p2.flat[void] = True
        splat(e2, void, 1.0)
        rank[void] = r

    assert sorted(rank.tolist()) == list(range(n)), "not a permutation"

    out = sys.stdout
    out.write("#pragma once\n\n")
    out.write("#include <cstdint>\n\n")
    out.write("// Generated by tools/bluenoise.py -- do not edit. A 64x64 void-and-cluster\n")
    out.write("// mask (Ulichney 1993, sigma 1.5): every rank 0..4095 once, row 0 first.\n")
    out.write("namespace ramdac\n{\n")
    out.write("constexpr int kBlueNoiseSize = %d;\n" % SIZE)
    out.write("constexpr uint16_t kBlueNoise[ %d ] = {\n" % n)
    for y in range(SIZE):
        row = rank[y * SIZE:(y + 1) * SIZE]
        out.write("\t" + ", ".join(str(int(v)) for v in row) + ",\n")
    out.write("};\n")
    out.write("} // namespace ramdac\n")


if __name__ == "__main__":
    main()
